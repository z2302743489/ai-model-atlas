import { readFile, writeFile, mkdir, rm, copyFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { snapshotValues, renderSnapshotHTML } from './snapshot.mjs';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const out = resolve(root, 'dist');
const read = (path) => readFile(resolve(root, path), 'utf8');
const json = async (path) => JSON.parse(await read(path));
const pretty = (value) => JSON.stringify(value, null, 2) + '\n';
const jsJSON = (value) => JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

export async function build({ quiet = false } = {}) {
  const [html, css, app, modelData, rankings, pricing, icons, iconSources, license] = await Promise.all([
    read('src/index.html'), read('src/styles.css'), read('src/app.js'),
    json('src/data/models.json'), json('src/data/arena-rankings.json'),
    json('src/data/pricing.json'), json('src/data/icons.json'),
    json('src/data/icons-sources.json'), read('licenses/LICENSE-LobeHub.txt'),
  ]);
  if (!Array.isArray(modelData.brands) || !Array.isArray(rankings.boards) || !Array.isArray(pricing.brands)) {
    throw new Error('数据缺少 brands 或 boards 数组。');
  }
  const snapshot = snapshotValues(modelData, rankings, pricing);
  const renderedHTML = renderSnapshotHTML(html, snapshot);
  const downloadData = { ...modelData, arena: rankings, pricing };
  const dataJS = [
    '// Generated by scripts/build.mjs. Edit src/data/*.json instead.',
    'const CHECKED=' + jsJSON(modelData.checkedAt) + ';',
    'const DATA=' + jsJSON(modelData.brands) + ';',
    'const RANKINGS=' + jsJSON(rankings) + ';',
    'const PRICING=' + jsJSON(pricing) + ';',
    'const ICONS=' + jsJSON(icons) + ';',
    'const ICON_SOURCES_DOWNLOAD="./icons-sources.json";',
    'const ICON_LICENSE_DOWNLOAD="./LICENSE-LobeHub.txt";',
    '',
  ].join('\n');
  await rm(out, { recursive: true, force: true });
  await mkdir(resolve(out, 'assets'), { recursive: true });
  await Promise.all([
    writeFile(resolve(out, 'index.html'), renderedHTML),
    writeFile(resolve(out, 'assets/style.css'), css),
    writeFile(resolve(out, 'assets/app.js'), app),
    writeFile(resolve(out, 'assets/data.js'), dataJS),
    writeFile(resolve(out, 'models.json'), pretty(downloadData)),
    writeFile(resolve(out, 'arena-rankings.json'), pretty(rankings)),
    writeFile(resolve(out, 'pricing.json'), pretty(pricing)),
    writeFile(resolve(out, 'icons-sources.json'), pretty(iconSources)),
    writeFile(resolve(out, 'LICENSE-LobeHub.txt'), license),
    writeFile(resolve(out, '.nojekyll'), ''),
    copyFile(resolve(root, 'THIRD_PARTY_NOTICES.md'), resolve(out, 'THIRD_PARTY_NOTICES.md')),
  ]);
  if (!quiet) console.log('Built dist/ (' + modelData.brands.length + ' brands, snapshot ' + modelData.checkedAt + ').');
  return { modelData, rankings, pricing, icons, iconSources, snapshot };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await build();
}
